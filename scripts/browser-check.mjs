import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../server.mjs';
const require=createRequire(import.meta.url);
const { chromium }=require('playwright');
const {app}=createApp({dataPath:join(mkdtempSync(join(tmpdir(),'pantry-browser-')),'state.json')});
const listener=app.listen(0,'127.0.0.1');await new Promise(r=>listener.once('listening',r));
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[],external=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:'))external.push(r.url());});
const checks=[];
try{
  await page.goto(`http://127.0.0.1:${listener.address().port}`);
  await page.locator('#connection').filter({hasText:'MCP 2025-11-25'}).waitFor();checks.push('MCP protocol negotiated');
  await page.getByRole('button',{name:'Check pantry & plan dinners'}).click();
  await page.getByText('Covered by recorded supplies').waitFor();checks.push('Two-dinner plan uses real tools');
  assert.equal(await page.locator('#revision').textContent(),'REV 0');checks.push('Preview leaves stock revision unchanged');
  await page.screenshot({path:'docs/desktop.png',fullPage:true});
  await page.getByRole('button',{name:'I’m cooking this'}).click();
  await page.getByText('Cooking recorded.').waitFor();
  assert.match(await page.locator('#receipts').textContent(),/Tomato rice/);checks.push('Confirmation consumes stock and records receipt');
  await page.reload();await page.locator('#connection').filter({hasText:'MCP'}).waitFor();
  assert.match(await page.locator('#receipts').textContent(),/Tomato pasta/);checks.push('Receipt survives reload');
  await page.getByRole('button',{name:'Check pantry & plan dinners'}).click();
  await page.getByText('Shopping gaps to resolve').waitFor();
  assert.equal(await page.locator('#confirm').count(),0);checks.push('Insufficient supplies prevent confirmation');
  await page.getByText('Add supplies you actually have',{exact:true}).click();
  await page.locator('#stock select').selectOption('tomato');await page.locator('#stock [name=portions]').fill('3');
  await page.getByRole('button',{name:'Add to pantry',exact:true}).click();
  await page.getByText('Pantry changed. Preview again before confirming.').waitFor();checks.push('Stock change invalidates displayed plan');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);checks.push('No horizontal overflow at 390px');
  await page.screenshot({path:'docs/mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);checks.push('No page errors or external requests');
  writeFileSync('docs/browser-check.json',JSON.stringify({at:new Date().toISOString(),checks,errors,external},null,2));
  console.log(JSON.stringify({checks},null,2));
}finally{await browser.close();await new Promise(r=>listener.close(r));}
